function makeWeeks(content) {
  return content.stages.map(([title, detail, target], index) => {
    const review = [
      ['오늘의 발견 한 줄', '잘된 시도 하나와 다음에 시도할 행동 하나를 아이의 말로 적어봐요.', '점수보다 실제로 해본 행동을 돌아봐요.'],
      ['나에게 도움이 된 말', '어려웠을 때 다시 시도하는 데 도움이 된 말이나 방법을 하나 정해요.', '부모는 답을 정하지 않고 먼저 들어주세요.'],
      ['내가 느낀 변화', '첫 주보다 편해진 점과 여전히 어려운 점을 하나씩 이야기해요.', '실천하기 어려웠다면 과제와 시간을 함께 조절해요.'],
      ['다음 한 걸음 정하기', '달라진 점을 인정하고 아이와 코치가 다음 달에 이어갈 목표를 하나 정해요.', '같은 목표를 이어가도 괜찮아요.'],
    ][index];
    return [
      { title, detail, minutes: index === 3 ? '경기 장면 · 5~10분' : '5~8분 · 조절 가능', target },
      index === 3
        ? { title: '같은 기준으로 다시 보기', detail: `새 경기에서 비교 가능한 장면을 기록하고 첫 기록과 살펴봐요. ${content.cue}`, minutes: '5~10분', target: '성공 여부와 함께 관찰 기회와 경기 조건도 확인해요.' }
        : { title: index === 0 ? '천천히 연결해보기' : index === 1 ? '선택하며 연결해보기' : '팀 훈련에서 시도해보기', detail: content.transfer, minutes: '5~8분 · 팀 훈련에 포함', target: content.cue },
      { title: review[0], detail: review[1], minutes: '5분 이내', target: review[2] },
    ];
  });
}

/**
 * Rule-based youth practice suggestions derived only from rated, observed skills.
 * @returns {{focus:string,label:string,title:string,personalized:boolean,sourceCount:number,note:string,weeks:Array<Array<{title:string,detail:string,minutes:string,target:string}>>}}
 */
export function deriveTrainingPlan(observations = []) {
  const rated = getScores(observations).filter(score => score.value !== null && score.count > 0);
  // SKILLS order provides a stable tie-breaker; unobserved skills never compete.
  const lowest = rated.reduce((selected, score) => !selected || score.value < selected.value ? score : selected, null);
  const focus = lowest?.id || 'scan';
  const content = CONTENT[focus];
  return {
    focus,
    label: SKILLS.find(skill => skill.id === focus).name,
    title: content.title,
    personalized: Boolean(lowest),
    sourceCount: lowest?.count || 0,
    note: LOAD_NOTE,
    weeks: makeWeeks(content),
  };
}
